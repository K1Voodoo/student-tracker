const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  loadData: () => ipcRenderer.invoke('data:load'),
  saveData: data => ipcRenderer.invoke('data:save', data),
  version: () => ipcRenderer.invoke('app:version'),
  dataPath: () => ipcRenderer.invoke('app:dataPath'),
  pickFiles: () => ipcRenderer.invoke('files:pick'),
  pickFolder: () => ipcRenderer.invoke('folder:pick'),
  openFile: p => ipcRenderer.invoke('file:open', p),
  revealFile: p => ipcRenderer.invoke('file:reveal', p),
  filesExist: paths => ipcRenderer.invoke('file:exists', paths),
  scanReports: args => ipcRenderer.invoke('reports:scan', args),
  exportBackup: data => ipcRenderer.invoke('backup:export', data),
  importBackup: () => ipcRenderer.invoke('backup:import'),
  runBackup: () => ipcRenderer.invoke('backup:run'),
  backupState: () => ipcRenderer.invoke('backup:state'),
  detectClouds: () => ipcRenderer.invoke('cloud:detect'),
  connectCloud: id => ipcRenderer.invoke('cloud:connect', id),
  ensureFolder: p => ipcRenderer.invoke('folder:ensure', p),
  listReportsFolder: folder => ipcRenderer.invoke('reports:listFolder', folder),
  pickAnyFolder: title => ipcRenderer.invoke('folder:pickAny', title),
  onBackup: cb => ipcRenderer.on('backup:done', (_e, r) => cb(r)),
  // detached field windows
  detachField: args => ipcRenderer.invoke('window:detach', args),
  patchStudentSync: (sid, changes) => ipcRenderer.sendSync('student:patch-sync', { sid, changes }),
  onStudentPatched: cb => ipcRenderer.on('student:patched', (_e, p) => cb(p)),
  onDataChanged: cb => ipcRenderer.on('data:changed', () => cb()),
  reattachField: args => ipcRenderer.invoke('window:reattach', args),
  onReattach: cb => ipcRenderer.on('field:reattach', (_e, a) => cb(a)),
  toggleMaximizeWindow: () => ipcRenderer.invoke('window:toggle-max'),
  onWindowMaximized: cb => ipcRenderer.on('window:maximized', (_e, m) => cb(m)),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  downloadUpdate: () => ipcRenderer.invoke('update:download'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: cb => ipcRenderer.on('update:status', (_e, s) => cb(s))
});
